<p class="my-2 [&amp;_strong:has(+br)]:inline-block [&amp;_strong:has(+br)]:pb-2"><strong>AODD Pumps</strong>: Again, 'A'. They can run dry without damage, making them reliable for applications where flow may be inconsistent.</p>
</li>

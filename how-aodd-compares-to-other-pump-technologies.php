<p class="my-2 [&amp;_strong:has(+br)]:inline-block [&amp;_strong:has(+br)]:pb-2"><strong>AODD Pumps</strong>: Rated &lsquo;A&rsquo; (Excellent). Their gentle pumping action makes them ideal for transferring shear-sensitive fluids without damaging product integrity.</p>
</li>
<li class="py-0 my-0 prose-p:pt-0 prose-p:mb-2 prose-p:my-0 [&amp;&gt;p]:pt-0 [&amp;&gt;p]:mb-2 [&amp;&gt;p]:my-0">
<p class="my-2 [&amp;_strong:has(+br)]:inline-block [&amp;_strong:has(+br)]:pb-2"><strong>Other Pump Types</strong>: Gear, piston/plunger, centrifugal, and vane pumps often rate poorly here. Only lobe pumps are rated as highly as AODD pumps for shear-sensitive applications.</p>
</li>
</ul>
